#!/usr/bin/env python3
"""Export minidoc-style comments from Python files to Markdown.

minidoc (https://gitlab.com/matsuori/minidoc) only scans C/C++. The Python
abstraction layer follows the same convention, and this script exports it in
the same Markdown layout as ``minidoc-export``:

    # (float lon, float lat, float scale = None)     <- optional arguments line
    # centres the map on a point                      <- free text
    def set_center(self, lon, lat, scale=None):

Rules (same as minidoc): the ``#`` comment must end on the line directly above
the declaration (or its decorators); a blank line in between means it is not a
doc. Module-level and class-level functions, classes and variables are
indexed; private names (leading underscore) are skipped, except ``__init__``.

Usage:  python tools/minidoc_py.py SOURCE_DIR [OUTPUT.md]
"""

import ast
import sys
from pathlib import Path


# (list lines, int decl_line)
# comment block that ends right above decl_line (1-based); list of strings
def comment_above(lines, decl_line):
    doc = []
    i = decl_line - 2
    while i >= 0 and lines[i].strip().startswith("#"):
        text = lines[i].strip().lstrip("#").strip()
        if not set(text) <= set("-=*"):          # skip separator lines
            doc.append(text)
        i -= 1
    return list(reversed(doc))


def _public(name):
    return not name.startswith("_") or name == "__init__"


# (Path path, Path root)
# list of (kind, qualname, signature, doc, line) entries for one file
def scan_file(path, root):
    source = path.read_text(encoding="utf-8")
    lines = source.splitlines()
    entries = []

    def visit(body, prefix):
        for node in body:
            first = min([node.lineno] + [d.lineno for d in getattr(node, "decorator_list", [])])
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and _public(node.name):
                doc = comment_above(lines, first)
                if doc:
                    sig = f"def {node.name}({ast.unparse(node.args)})"
                    entries.append(("function", prefix + node.name, sig, doc, node.lineno))
            elif isinstance(node, ast.ClassDef) and _public(node.name):
                doc = comment_above(lines, first)
                if doc:
                    bases = ", ".join(ast.unparse(b) for b in node.bases)
                    sig = f"class {node.name}({bases})" if bases else f"class {node.name}"
                    entries.append(("class", prefix + node.name, sig, doc, node.lineno))
                visit(node.body, prefix + node.name + ".")
            elif isinstance(node, (ast.Assign, ast.AnnAssign)):
                targets = node.targets if isinstance(node, ast.Assign) else [node.target]
                names = [t.id for t in targets if isinstance(t, ast.Name) and _public(t.id)]
                doc = comment_above(lines, node.lineno) if names else []
                if doc:
                    entries.append(("variable", prefix + names[0], "", doc, node.lineno))
            # attributes documented in __init__ (self.x = ...)
            if isinstance(node, ast.FunctionDef) and node.name == "__init__":
                for stmt in node.body:
                    if (isinstance(stmt, ast.Assign) and len(stmt.targets) == 1
                            and isinstance(stmt.targets[0], ast.Attribute)
                            and _public(stmt.targets[0].attr)):
                        doc = comment_above(lines, stmt.lineno)
                        if doc:
                            entries.append(("variable", prefix + stmt.targets[0].attr,
                                            "", doc, stmt.lineno))

    visit(ast.parse(source).body, "")
    return entries


def _split_args(doc):
    if doc and doc[0].startswith("(") and doc[0].endswith(")"):
        return doc[0], doc[1:]
    return None, doc


def _cell(s):
    return s.replace("|", "\\|")


# (Path root)
# Markdown for every .py file below root, one section per file
def export(root):
    out = [f"# Python API (`{root.name}/`)", "",
           "Generated by `tools/minidoc_py.py` from minidoc-style comments.", ""]
    for path in sorted(root.rglob("*.py")):
        entries = scan_file(path, root)
        if not entries:
            continue
        out += [f"## `{path.relative_to(root.parent).as_posix()}`", ""]
        for title, kinds in (("Classes", ("class",)), ("Functions", ("function",))):
            group = [e for e in entries if e[0] in kinds]
            if not group:
                continue
            out += [f"### {title}", ""]
            for _, name, sig, doc, line in group:
                args, text = _split_args(doc)
                out += [f"#### `{name}`", "", "```python", sig, "```", ""]
                if args:
                    out.append(f"- **Arguments:** `{args}`")
                out += [f"- **Line:** {line}", ""]
                if text:
                    out += [" ".join(text), ""]
        variables = [e for e in entries if e[0] == "variable"]
        if variables:
            out += ["### Variables", "", "| Name | Description | Line |",
                    "|------|-------------|------|"]
            for _, name, _, doc, line in variables:
                out.append(f"| `{name}` | {_cell(' '.join(doc))} | {line} |")
            out.append("")
    return "\n".join(out)


def main(argv):
    if len(argv) < 2:
        print(__doc__.strip().splitlines()[-1], file=sys.stderr)
        return 2
    text = export(Path(argv[1]).resolve())
    if len(argv) > 2:
        Path(argv[2]).write_text(text, encoding="utf-8")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
